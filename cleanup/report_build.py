#!/usr/bin/env python3
"""report_build.py 1.0.0 - CLEANUP_REPORT_2026-10-21.md from omni_lab model_deletion rows + the executor logs.

Every number in the report is read from a record: model_deletion (what was removed, bytes, recipe, ids),
exec_<volume>.out (gate refusals and failures), ws_cleanup_log.jsonl, and the df snapshots. Nothing is typed in.

    C:/Python314/python.exe cleanup/report_build.py --plan cleanup_plan.json --logs <dir with exec_*.out, df files> \
        --ws-log cleanup/inputs/ws_cleanup_log.jsonl --out <report.md>
"""
from __future__ import annotations

import argparse
import json
import os
import sys
from collections import defaultdict
from pathlib import Path

HERE = Path(__file__).resolve().parent
sys.path.insert(0, str(HERE.parent))
import omni_lab_db as db  # noqa: E402

GB = 1e9
GIB = 1024 ** 3


def jl(path):
    out = []
    if not os.path.exists(path):
        return out
    for line in open(path, encoding="utf-8", errors="replace"):
        line = line.strip()
        if line.startswith("{"):
            try:
                out.append(json.loads(line))
            except json.JSONDecodeError:
                pass
    return out


def main() -> int:
    ap = argparse.ArgumentParser()
    ap.add_argument("--plan", required=True)
    ap.add_argument("--logs", required=True)
    ap.add_argument("--ws-log", required=True)
    ap.add_argument("--out", required=True)
    ap.add_argument("--extra", default=None, help="markdown fragment appended verbatim (W0, deviations, df table)")
    args = ap.parse_args()
    plan = json.load(open(args.plan, encoding="utf-8"))
    conn = db.connect("ro", app="cleanup-report")
    cur = conn.cursor()
    cur.execute("SELECT d.id, h.name, d.unit_path, d.plan_wave, d.plan_index, d.status, d.size_bytes_du, d.weight_bytes, "
                "d.file_count, d.layout, d.parameter_count, d.digest_mode, d.listing_sha256, d.recipe_archive_path, "
                "d.recipe_archive_sha256, jsonb_array_length(d.recipe_files), d.affected_model_ids, d.ledger_checkpoint_id, "
                "d.ledger_receipt_sha, d.df_before, d.df_after, d.error, m.model_key, d.duplicate_of_model_id "
                "FROM model_deletion d JOIN host h ON h.id = d.host_id JOIN model m ON m.id = d.model_id ORDER BY d.plan_wave, d.size_bytes_du DESC")
    rows = cur.fetchall()
    cur.execute("SELECT status, count(*) FROM model GROUP BY 1 ORDER BY 1")
    model_status = cur.fetchall()
    conn.close()

    by_wave = defaultdict(list)
    for r in rows:
        by_wave[r[3]].append(r)
    logs = {v: jl(os.path.join(args.logs, f"exec_{v}.out")) for v in ("nas", "home", "lexar")}
    ws = jl(args.ws_log)
    sd = plan["server_delete"]

    L = []
    w = L.append
    w("# Cleanup report: experimental weights, 2026-10-21")
    w("")
    w("Owner order (Cyril, 2026-10-21, verbatim): \"" + plan["owner_order_verbatim"] + "\"")
    w("")
    w("Plan: `CLEANUP_PLAN_2026-10-21.md` / `omni-lab/cleanup_plan.json`, with the lead review's corrections "
      "(27 server units moved out of DELETE; 16 workstation worktrees routed to Codex). Generated by "
      "`omni-lab/cleanup/report_build.py` from omni_lab `model_deletion` and the executor logs.")
    w("")
    if args.extra and os.path.exists(args.extra):
        w(open(args.extra, encoding="utf-8").read().rstrip())
        w("")

    w("## Deleted, by wave (from omni_lab model_deletion)")
    w("")
    w("| Wave | Deleted | du bytes removed | Failed / other |")
    w("|---|---:|---:|---|")
    for wave in sorted(by_wave):
        rs = by_wave[wave]
        ok = [r for r in rs if r[5] == "deleted"]
        bad = [r for r in rs if r[5] != "deleted"]
        w(f"| {wave} | {len(ok)} | {sum(r[6] for r in ok):,} ({sum(r[6] for r in ok)/GB:.1f} GB) | "
          f"{', '.join(f'{r[5]}: `{r[2]}`' for r in bad) or '-'} |")
    w("")
    w("`du bytes` is the inventory `du -sb` of each unit (server) or the worktree size (workstation). The df tables "
      "above are the measured effect. Each deleted unit's record is the `model_deletion` row named; its recipe "
      "archive holds MANIFEST.tsv (every removed file: size, mtime, sha256 or header sha256), DELETION_RECEIPT.json "
      "and the copied non-weight files under `tree/`.")
    w("")
    for wave in sorted(by_wave):
        rs = [r for r in by_wave[wave] if r[5] == "deleted"]
        if not rs:
            continue
        w(f"### {wave}: {len(rs)} items")
        w("")
        if wave == "W4-WS":
            w("| GiB | path | model_deletion | model | rebuild source |")
            w("|---:|---|---:|---|---|")
            for r in rs:
                w(f"| {r[6]/GIB:.2f} | `{r[2]}` | {r[0]} | `{r[22]}` | `{r[13]}` |")
        else:
            w("| GB (du) | files | params | digest | path | model_deletion | ledger | recipe archive |")
            w("|---:|---:|---:|---|---|---:|---|---|")
            for r in rs:
                dg = "full" if r[11] == "full-sha256" else "idx+hdr"
                params = f"{r[10]:,}" if r[10] else "-"
                led = f"{r[17]} ({(r[18] or '')[:12]})" if r[17] else "-"
                w(f"| {r[6]/GB:.2f} | {r[8]} | {params} | {dg} | `{r[2]}` | {r[0]} | {led} | `{r[13]}` |")
        w("")

    w("## Not deleted: refused by the per-unit gate (needs a ruling)")
    w("")
    w("The executor re-checked every approved unit just before deleting it. These were refused and left untouched. "
      "Reasons are quoted from `exec_<volume>.out` (truncated).")
    w("")
    w("| GB | path | reasons |")
    w("|---:|---|---|")
    blocked_total = 0
    for v in ("nas", "home", "lexar"):
        for e in logs[v]:
            if e.get("step") == "BLOCKED":
                idx = e.get("plan_index")
                gb = sd[idx]["size_gb"] if isinstance(idx, int) else 0
                blocked_total += sd[idx]["size_bytes_du"] if isinstance(idx, int) else 0
                rs = "; ".join(x[:260].replace("|", "/") for x in e.get("reasons", []))
                w(f"| {gb} | `{e['unit']}` | {rs} |")
    w("")
    w(f"Total refused: {blocked_total/GB:.1f} GB.")
    w("")
    fails = [e for v in logs for e in logs[v] if e.get("step") == "FAILED"]
    ends = [e for v in logs for e in logs[v] if e.get("step") in ("end", "stop")]
    if fails:
        w("## Failures (the wave stopped at these)")
        w("")
        for e in fails:
            w(f"- `{e.get('unit')}`: {e.get('error', '')[:600]}")
        w("")
    w("## Worker end states")
    w("")
    for e in ends:
        w(f"- {e.get('volume')}: {e.get('step')} at {e.get('ts')}: deleted {e.get('deleted')}, blocked {e.get('blocked')}")
    ws_end = [e for e in ws if e.get("step") in ("end", "children-REMOVED", "children-SKIPPED")]
    for e in ws_end:
        w(f"- workstation: {e.get('step')} at {e.get('ts')}: " + json.dumps({k: v for k, v in e.items() if k not in ('ts', 'step', 'files')})[:300])
    w("")
    w("## omni_lab model status after the cleanup")
    w("")
    w("| status | rows |")
    w("|---|---:|")
    for s, n in model_status:
        w(f"| {s} | {n} |")
    w("")
    with open(args.out, "w", encoding="utf-8", newline="\n") as fh:
        fh.write("\n".join(L) + "\n")
    print(f"wrote {args.out}: {len(rows)} model_deletion rows")
    return 0


if __name__ == "__main__":
    sys.exit(main())
