"""Fail-closed separation of model, folding-evidence, and evaluation horizons.

Sequence length is not one setting.  A model's architectural context capacity,
the positions represented by immutable folding evidence, and the number of
tokens generated by a behavior evaluator are independent contracts.  This
module gives each one a distinct name and produces an auditable report so an
evaluation rollout limit cannot silently masquerade as a folding horizon.
"""

from __future__ import annotations

import copy
from collections.abc import Mapping, Sequence
from typing import Any


SEQUENCE_HORIZON_SCHEMA = "neural-forge-sequence-horizon-contract-v1"

_CONTEXT_CAPACITY_FIELDS = (
    "max_position_embeddings",
    "n_positions",
    "max_sequence_length",
    "seq_length",
    "context_length",
)
_POSITIONAL_SEMANTIC_FIELDS = (
    "max_position_embeddings",
    "n_positions",
    "max_sequence_length",
    "seq_length",
    "context_length",
    "rope_parameters",
    "rope_theta",
    "rope_scaling",
    "rotary_emb_base",
    "partial_rotary_factor",
    "sliding_window",
    "use_sliding_window",
)


class SequenceHorizonContractError(RuntimeError):
    """A sequence-horizon contract was ambiguous or internally inconsistent."""


def _config_payload(config: Any) -> dict[str, Any]:
    reporter = getattr(config, "to_dict", None)
    value = reporter() if callable(reporter) else config
    if not isinstance(value, Mapping):
        raise SequenceHorizonContractError(
            "A model context contract requires a configuration mapping."
        )
    return copy.deepcopy(dict(value))


def _positive_int(value: Any, name: str) -> int:
    if isinstance(value, bool):
        raise SequenceHorizonContractError(f"{name} must be a positive integer.")
    try:
        result = int(value)
    except (TypeError, ValueError) as exc:
        raise SequenceHorizonContractError(
            f"{name} must be a positive integer."
        ) from exc
    if result <= 0:
        raise SequenceHorizonContractError(f"{name} must be a positive integer.")
    return result


def model_context_contract(config: Any) -> dict[str, Any]:
    """Extract architectural context capacity and positional semantics."""

    payload = _config_payload(config)
    capacity_field = next(
        (
            name
            for name in _CONTEXT_CAPACITY_FIELDS
            if payload.get(name) is not None
        ),
        None,
    )
    if capacity_field is None:
        raise SequenceHorizonContractError(
            "Model configuration exposes no recognized context-capacity field."
        )
    capacity = _positive_int(
        payload[capacity_field],
        f"model config {capacity_field}",
    )
    semantics = {
        name: copy.deepcopy(payload[name])
        for name in _POSITIONAL_SEMANTIC_FIELDS
        if name in payload
    }
    return {
        "capacity_tokens": capacity,
        "capacity_field": capacity_field,
        "positional_semantics": semantics,
    }


def assert_model_context_preserved(
    parent_config: Any,
    child_config: Any,
) -> dict[str, Any]:
    """Prove a same-family structural target did not inherit a short limit."""

    parent = model_context_contract(parent_config)
    child = model_context_contract(child_config)
    if parent != child:
        raise SequenceHorizonContractError(
            "Structural target changed context capacity or positional semantics."
        )
    return {
        "parent": parent,
        "child": child,
        "capacity_and_positional_semantics_preserved": True,
    }


def folding_evidence_horizon(trace_manifest: Mapping[str, Any]) -> dict[str, Any]:
    """Summarize the actual positions represented by an immutable trace cache."""

    if not isinstance(trace_manifest, Mapping):
        raise SequenceHorizonContractError("Trace manifest must be a mapping.")
    capture = trace_manifest.get("capture")
    corpus = trace_manifest.get("corpus")
    if not isinstance(capture, Mapping) or not isinstance(corpus, Mapping):
        raise SequenceHorizonContractError(
            "Trace manifest must contain capture and corpus mappings."
        )
    sample_last_tokens = _positive_int(
        capture.get("sample_last_tokens"),
        "trace sample_last_tokens",
    )
    configured_decode_ceiling = _positive_int(
        capture.get("max_decode_steps"),
        "trace max_decode_steps",
    )
    prompt_counts = corpus.get("prompt_token_counts")
    forced_counts = corpus.get("forced_decode_token_counts")
    if (
        not isinstance(prompt_counts, Sequence)
        or isinstance(prompt_counts, (str, bytes))
        or not isinstance(forced_counts, Sequence)
        or isinstance(forced_counts, (str, bytes))
        or not prompt_counts
        or len(prompt_counts) != len(forced_counts)
    ):
        raise SequenceHorizonContractError(
            "Trace corpus token-count vectors must be nonempty and aligned."
        )
    prompts = tuple(
        _positive_int(value, f"prompt_token_counts[{index}]")
        for index, value in enumerate(prompt_counts)
    )
    continuations = tuple(
        _positive_int(value, f"forced_decode_token_counts[{index}]")
        for index, value in enumerate(forced_counts)
    )
    if max(continuations) > configured_decode_ceiling:
        raise SequenceHorizonContractError(
            "Trace corpus exceeds its configured decode ceiling."
        )
    final_prefixes = tuple(
        prompt + continuation
        for prompt, continuation in zip(prompts, continuations, strict=True)
    )
    retained_prefill_rows = sum(
        min(prompt, sample_last_tokens) for prompt in prompts
    )
    retained_decode_rows = sum(continuations)
    return {
        "batch_count": len(prompts),
        "configured_decode_ceiling_tokens": configured_decode_ceiling,
        "prefill_tail_rows_per_batch": sample_last_tokens,
        "minimum_prompt_tokens": min(prompts),
        "maximum_prompt_tokens": max(prompts),
        "minimum_observed_continuation_tokens": min(continuations),
        "maximum_observed_continuation_tokens": max(continuations),
        "minimum_observed_full_prefix_tokens": min(final_prefixes),
        "maximum_observed_full_prefix_tokens": max(final_prefixes),
        "retained_prefill_rows": retained_prefill_rows,
        "retained_decode_rows": retained_decode_rows,
        "retained_causal_rows": retained_prefill_rows + retained_decode_rows,
        "full_prefill_history_retained": all(
            prompt <= sample_last_tokens for prompt in prompts
        ),
        "evidence_is_behavioral_sample_not_model_capacity": True,
    }


def evaluation_rollout_contract(maximum_new_tokens: int) -> dict[str, Any]:
    """Describe a generation stopping condition without broadening its scope."""

    return {
        "maximum_new_tokens": _positive_int(
            maximum_new_tokens,
            "evaluation maximum_new_tokens",
        ),
        "purpose": "candidate_behavior_rollout_stopping_condition_only",
        "used_as_model_context_capacity": False,
        "used_as_folding_evidence_horizon": False,
        "used_as_consumer_fit_row_limit": False,
        "used_to_select_or_limit_sealed_cache_batches": False,
        "evaluation_only": True,
    }


def build_sequence_horizon_contract(
    *,
    parent_config: Any,
    child_config: Any,
    trace_manifest: Mapping[str, Any],
    evaluation_maximum_new_tokens: int | None = None,
    behavioral_probe_prefixes: Sequence[int] = (64, 256, 1024),
) -> dict[str, Any]:
    """Build one report while keeping every horizon independently named."""

    model = assert_model_context_preserved(parent_config, child_config)
    evidence = folding_evidence_horizon(trace_manifest)
    probes = tuple(
        _positive_int(value, f"behavioral_probe_prefixes[{index}]")
        for index, value in enumerate(behavioral_probe_prefixes)
    )
    if tuple(sorted(set(probes))) != probes:
        raise SequenceHorizonContractError(
            "behavioral_probe_prefixes must be unique and ascending."
        )
    capacity = int(model["child"]["capacity_tokens"])
    if probes and max(probes) > capacity:
        raise SequenceHorizonContractError(
            "A requested behavioral probe exceeds model context capacity."
        )
    observed = int(evidence["maximum_observed_full_prefix_tokens"])
    probe_coverage = {
        str(prefix): observed >= prefix
        for prefix in probes
    }
    evaluation = None
    if evaluation_maximum_new_tokens is not None:
        evaluation = evaluation_rollout_contract(
            evaluation_maximum_new_tokens
        )
    uncovered = [
        prefix for prefix in probes if not probe_coverage[str(prefix)]
    ]
    return {
        "schema": SEQUENCE_HORIZON_SCHEMA,
        "model_context": model,
        "folding_evidence": evidence,
        "evaluation_rollout": evaluation,
        "behavioral_prefix_probe_coverage": probe_coverage,
        "uncovered_behavioral_prefixes": uncovered,
        "folding_evidence_covers_all_requested_prefixes": not uncovered,
        "long_context_behavior_preserved": None,
        "long_context_behavior_proven": False,
        "long_context_behavior_requires_explicit_child_probe": True,
        "limits_are_independently_named_and_bound": True,
        "evaluation_limit_can_cap_folding": False,
    }


