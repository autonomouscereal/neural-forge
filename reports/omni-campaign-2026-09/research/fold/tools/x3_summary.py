#!/usr/bin/env python3
"""x3_summary.py -- collect every graded X3 checkpoint into SUMMARY.json / SUMMARY.md.

Primary column = content passes on Codex's held oracles (artifact-tolerant), paired against the untrained C2 child
with an exact McNemar test.  Retention, artifacts and bank terminations are printed as diagnostics.  The kill rule
of the critique ("no positive content slope across the rungs") is evaluated per arm and printed with its numbers;
with 162 tasks a slope is a direction signal, not a promotion.
"""
from __future__ import annotations

import argparse
import json
import sys
from pathlib import Path

sys.path.insert(0, str(Path(__file__).resolve().parent))
import fold_common as fc  # noqa: E402

ARMS = {"kd": [250000, 500000, 1000000, 2000000], "opd": [250000, 500000, 1000000, 2000000],
        "kd1m-opd": [250000, 500000, 1000000]}


def slope(xs, ys):
    n = len(xs)
    if n < 2:
        return None
    mx, my = sum(xs) / n, sum(ys) / n
    den = sum((x - mx) ** 2 for x in xs)
    return sum((x - mx) * (y - my) for x, y in zip(xs, ys)) / den if den else None


def main(argv=None) -> None:
    p = argparse.ArgumentParser()
    p.add_argument("--root", required=True)
    args = p.parse_args(argv)
    root = Path(args.root)
    rows = []

    def load(label):
        g = root / "eval" / label / "grade.json"
        pr = root / "eval" / label / "pair_vs_c2k896.json"
        if not g.exists():
            return None
        grade = json.loads(g.read_text(encoding="utf-8"))
        pair = json.loads(pr.read_text(encoding="utf-8")) if pr.exists() else None
        s = grade.get("semantic", {})
        ret = (grade.get("retention") or {}).get("summary")
        row = {"label": label, "content": s.get("content_pass"), "n": s.get("n"), "strict": s.get("strict_pass"),
               "classes": s.get("classes"),
               "text": sum(v.get("content_pass", 0) for k, v in s.get("by_route", {}).items() if k.startswith("text_")),
               "tool": sum(v.get("content_pass", 0) for k, v in s.get("by_route", {}).items() if k.startswith("tool_")),
               "retention_diag": {h: v["matches"] for h, v in ret["consecutive_prefix"].items()} if ret else None,
               "retention_eligible": {h: v["eligible"] for h, v in ret["consecutive_prefix"].items()} if ret else None,
               "bank_terms": {k: grade["bank_v1"][k] for k in ("eos", "capped", "empty", "loop")} if "bank_v1" in grade else None,
               "vs_c2k896": pair["content_pooled"] if pair else None, "checkpoint": grade["run"]["checkpoint_sha256"]}
        rows.append(row)
        return row

    load("parent")
    base = load("c2k896")
    verdicts = {}
    for arm, rungs in ARMS.items():
        got = [(r, load(f"{arm}-{r}")) for r in rungs]
        got = [(r, row) for r, row in got if row]
        if got and base:
            xs = [0] + [r / 1e6 for r, _ in got]
            ys = [base["content"]] + [row["content"] for _, row in got]
            sl = slope(xs, ys)
            verdicts[arm] = {"rungs_graded": [r for r, _ in got], "content": ys, "slope_per_M_tokens": sl,
                             "positive_slope": sl is not None and sl > 0,
                             "best_vs_c2k896": max((row["vs_c2k896"] for _, row in got if row["vs_c2k896"]),
                                                   key=lambda v: v["gained"] - v["lost"], default=None)}
    summary = {"schema": "fold-research.x3-summary.v1", "created_utc": fc_utc(), "rows": rows, "arms": verdicts,
               "kill_rule": "an arm is closed when its content slope across 0 / 0.25 / 0.5 / 1 / 2M tokens is not positive",
               "reading": "content = Codex oracle passes (artifact-tolerant) on 162 held tasks; retention / artifacts / "
                          "bank terminations are diagnostics; bank v1 answers are in eval/<label>/bank_v1_answers.md"}
    fc.write_json(root / "SUMMARY.json", summary)
    lines = ["# X3 0.8B ladder -- summary (generated by x3_summary.py; numbers read from eval/*/grade.json)", "",
             "| checkpoint | content /162 | text /44 | tool /118 | vs C2 lost/gained (McNemar p) | ret exact 8/16/32 (diag) | bank eos/cap/empty/loop (diag) |",
             "|---|---|---|---|---|---|---|"]
    for r in rows:
        v = r["vs_c2k896"]
        vs = f"{v['lost']}/{v['gained']} (p={v['mcnemar_p']:.3g})" if v else "-"
        ret = "/".join(str(r["retention_diag"][h]) for h in ("8", "16", "32")) if r["retention_diag"] else "self"
        bt = "/".join(str(r["bank_terms"][k]) for k in ("eos", "capped", "empty", "loop")) if r["bank_terms"] else "-"
        lines.append(f"| {r['label']} | {r['content']} | {r['text']} | {r['tool']} | {vs} | {ret} | {bt} |")
    lines += ["", "## Kill rule per arm", ""]
    for arm, v in verdicts.items():
        lines.append(f"- **{arm}**: content {v['content']} at 0 + {v['rungs_graded']} tokens; slope "
                     f"{v['slope_per_M_tokens']} per M tokens -> {'positive' if v['positive_slope'] else 'NOT positive (close the arm)'}")
    (root / "SUMMARY.md").write_text("\n".join(lines) + "\n", encoding="utf-8")
    print("\n".join(lines))


def fc_utc():
    import time
    return time.strftime("%Y-%m-%dT%H:%M:%SZ", time.gmtime())


if __name__ == "__main__":
    main()
