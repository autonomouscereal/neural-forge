#!/usr/bin/env python3
"""tool_pins.py -- $OC/distill/tools/TOOL_PINS.json: every deployed Stage D tool with its version, sha256, path and
superseded copies, GENERATED by reading the files (card X-T3; STAGE_D_RECONCILED_PLAN_2026-10-14 section 7.2).
Written 2026-10-14 by Claude, lane infra.  Standard library only.

Why: tests that hard-code a tool's sha or version break whenever the tool is legitimately bumped (on 10-14 the 1.3.3
trainer and qtext 1.0.6 failed 14 Codex tests on pin drift).  A test reads the pin from here instead; whoever deploys
regenerates the file, and `verify` says whether what is on disk is still what was pinned.

Commands
  generate [--root DIR] [--out PATH] [--only NAME ...]
           scan and write the pins (the previous file is kept in tools/_superseded/).  --only (1.1.0, the deployed-only
           mode): re-pin ONLY the named files (tools/ names such as intake.py or speech/asr_two_judge.py, installed
           paths such as queues/gpu6.sh) and copy every other entry unchanged from the current pins, so a deploy never
           blesses another lane's in-flight edits (their DRIFT / UNPINNED lines stay for their owner to see).  Every
           name must exist on disk; the current pins must exist.  A whole-tree `generate` is for the infra lane only.
  verify   [--root DIR] [--pins PATH] [--allow-unpinned]
           re-hash every pinned file; exit 1 on a changed sha or version, a missing file, or (unless allowed) a
           deployed file that is not pinned; prints one line per problem and a count line
  get NAME [--pins PATH]              one entry as JSON (NAME = a tools/ file name, e.g. streamed_kd_trainer.py, or an
                                      installed path relative to the root, e.g. queues/gpu6.sh); exit 1 if absent

What is scanned (relative to --root, default /home/cereal/omni-campaign/distill):
  tools       tools/*.py, tools/*.sh                          (the deployed tools, their tests and drivers)
              tools/speech/*.py|sh, tools/speech/tests/*.py|sh (1.1.0: the speech lane; pinned as speech/<name>)
  installed   queues/*.py, queues/*.sh, queues/frozen/**/*.py|sh  (installed queue copies and frozen tool copies)
  superseded  tools/_superseded/**, tools/_superseded_local/**, tools/_prev/**, tools/backups/**, tools/.bak-*/**,
              tools/speech/_superseded/**,
              queues/<name>.<suffix> backups of an installed file, frozen <stem>.<sha16>.py refreeze archives
  not scanned tools/_staging_*/ (staged, not deployed), __pycache__, .pytest_cache
Versions are read from the file text, never typed in: the first of TOOL_VERSION / __version__ / VERSION /
<NAME>_VERSION (not *NUMERICS*/*EXPECTED*/*SCHEMA*) assignments in the first 400 lines; `version` is the last
x.y.z token of that string, `version_string` the whole string; a file without one is pinned by sha only.
A superseded file belongs to a pinned file F (stem S) when its name is F.<anything>, S_<digit...>, S.<16 hex>.<ext>,
or F itself inside a superseded directory.
"""

from __future__ import annotations

import argparse
import hashlib
import json
import os
import re
import sys
import time
from pathlib import Path

TOOL_NAME = "tool_pins"
TOOL_VERSION = "1.1.0"   # 1.0.0 (2026-10-14): first version, card X-T3
#                          1.1.0 (2026-10-15, intake review item 7): generate --only (deployed-only re-pin, every other
#                          entry copied from the current pins); tools/speech and tools/speech/tests are pinned
SCHEMA = "omni-campaign.tool-pins.v1"
DEFAULT_ROOT = "/home/cereal/omni-campaign/distill"
CODE_EXT = (".py", ".sh")
SUPERSEDED_DIRS = ("tools/_superseded", "tools/_superseded_local", "tools/_prev", "tools/backups", "tools/speech/_superseded")
TOOL_SUBDIRS = ("speech", "speech/tests")   # pinned as "<subdir>/<name>" (names repeat across dirs: conftest.py)
SKIP_PARTS = {"__pycache__", ".pytest_cache"}
PREFERRED = ("TOOL_VERSION", "__version__", "VERSION")
SKIP_VERSION_WORDS = ("NUMERICS", "EXPECTED", "SCHEMA", "MIN_", "REQUIRED", "BASELINE")
ASSIGN = re.compile(r"""^\s*(?:export\s+)?([A-Za-z_][A-Za-z0-9_]*)\s*=\s*(?:"([^"\n]*)"|'([^'\n]*)'|([^\s#'"]+))""")
SEMVER = re.compile(r"\d+\.\d+\.\d+(?:[.\-+][0-9A-Za-z]+)*")
HEX16 = re.compile(r"^[0-9a-f]{16}$")


def utc(epoch: float | None = None) -> str:
    return time.strftime("%Y-%m-%dT%H:%M:%SZ", time.gmtime(time.time() if epoch is None else epoch))


def sha256_file(path: Path) -> str:
    h = hashlib.sha256()
    with open(path, "rb") as handle:
        for chunk in iter(lambda: handle.read(1 << 20), b""):
            h.update(chunk)
    return h.hexdigest()


def read_version(path: Path) -> tuple[str | None, str | None, str]:
    """(version, version_string, source) read from the file's own assignments."""
    found: dict[str, str] = {}
    order: list[str] = []
    try:
        with open(path, encoding="utf-8", errors="replace") as handle:
            for i, line in enumerate(handle):
                if i >= 400:
                    break
                m = ASSIGN.match(line)
                if not m or not (m.group(1) == "__version__" or m.group(1).endswith("VERSION")):
                    continue
                name = m.group(1)
                if any(w in name for w in SKIP_VERSION_WORDS) or name in found:
                    continue
                found[name] = next(g for g in m.groups()[1:] if g is not None)
                order.append(name)
    except OSError:
        return None, None, "unreadable"
    pick = next((n for n in PREFERRED if n in found), order[0] if order else None)
    if pick is None:
        return None, None, "none"
    text = found[pick].strip()
    tokens = SEMVER.findall(text)
    return (tokens[-1] if tokens else text), text, pick


def kind_of(name: str) -> str:
    if name.startswith("test_") or name == "conftest.py":
        return "test"
    if name.startswith("queue_") or (name.startswith("gpu") and name.endswith(".sh")):
        return "queue"
    if name.startswith(("run_", "install_", "wait_")):
        return "driver"
    return "tool" if name.endswith(".py") else "script"


def describe(root: Path, path: Path) -> dict:
    st = path.stat()
    version, vstring, source = read_version(path)
    return {"path": str(path.relative_to(root)).replace(os.sep, "/"), "sha256": sha256_file(path), "bytes": st.st_size,
            "mtime_utc": utc(st.st_mtime), "version": version, "version_string": vstring, "version_source": source}


def skipped(rel_parts: tuple[str, ...]) -> bool:
    return any(p in SKIP_PARTS for p in rel_parts) or any(p.startswith("_staging") for p in rel_parts)


def tool_key(root: Path, path: Path) -> str:
    """The pins['tools'] key: the file name for tools/<name>, "<subdir>/<name>" for the pinned sub-directories."""

    return path.relative_to(root / "tools").as_posix()


def scan(root: Path) -> tuple[list[Path], list[Path], list[Path]]:
    tools = sorted(p for p in (root / "tools").glob("*") if p.is_file() and p.suffix in CODE_EXT)
    for sub in TOOL_SUBDIRS:
        tools += sorted(p for p in (root / "tools" / sub).glob("*") if p.is_file() and p.suffix in CODE_EXT)
    installed = sorted(p for p in (root / "queues").glob("*") if p.is_file() and p.suffix in CODE_EXT)
    frozen_dir = root / "queues" / "frozen"
    if frozen_dir.is_dir():
        for p in sorted(frozen_dir.rglob("*")):
            if p.is_file() and p.suffix in CODE_EXT and not skipped(p.relative_to(root).parts):
                installed.append(p)
    superseded: list[Path] = []
    dirs = [root / d for d in SUPERSEDED_DIRS] + sorted(p for p in (root / "tools").glob(".bak-*") if p.is_dir())
    for d in dirs:
        if d.is_dir():
            superseded += [p for p in sorted(d.rglob("*")) if p.is_file() and not skipped(p.relative_to(root).parts)
                           and not p.name.endswith((".pyc", ".json", ".md", ".txt", ".log"))]
    # queues/<installed file>.<suffix> backups (gpu6.sh.1.2.0-live-20261014) and frozen refreeze archives
    names = {p.name for p in installed}
    for p in sorted((root / "queues").glob("*")):
        if p.is_file() and p not in installed and any(p.name.startswith(n + ".") for n in names):
            superseded.append(p)
    archived = [p for p in installed if "frozen" in p.relative_to(root).parts and "." in p.stem
                and HEX16.match(p.stem.rsplit(".", 1)[-1])]  # k3_teacher_cache-gpu6.<sha16>.py (REFREEZE archive)
    for p in archived:
        installed.remove(p)
        superseded.append(p)
    return tools, installed, superseded


def belongs(sup: Path, live: Path, in_superseded_dir: bool) -> bool:
    f, s, b = live.name, live.stem, sup.name
    if b.startswith(f + "."):
        return True
    if b.startswith(s + "_") and len(b) > len(s) + 1 and b[len(s) + 1].isdigit():
        return True
    head, _, ext = b.rpartition(".")
    if head.startswith(s + ".") and HEX16.match(head[len(s) + 1:]) and "." + ext == live.suffix:
        return True
    return in_superseded_dir and b == f


def build(root: Path) -> dict:
    root = root.resolve()
    tools, installed, superseded = scan(root)
    sup_desc = {p: describe(root, p) for p in superseded}
    claimed: set[Path] = set()

    def entry(p: Path) -> dict:
        e = describe(root, p)
        e["name"] = p.stem
        e["kind"] = kind_of(p.name)
        mine = [q for q in superseded if belongs(q, p, q.parent != root / "queues")]
        claimed.update(mine)
        e["superseded"] = sorted((sup_desc[q] for q in mine), key=lambda d: (d["mtime_utc"], d["path"]))
        return e

    tool_entries = {tool_key(root, p): entry(p) for p in tools}
    by_sha: dict[str, list[str]] = {}
    for name, e in tool_entries.items():
        by_sha.setdefault(e["sha256"], []).append(name)
    inst_entries = {}
    for p in installed:
        e = entry(p)
        e["same_as_tools"] = by_sha.get(e["sha256"], [])
        inst_entries[e["path"]] = e
    orphans = sorted((sup_desc[q] for q in superseded if q not in claimed), key=lambda d: d["path"])
    core = core_of({"tools": tool_entries, "installed": inst_entries})
    me = Path(__file__).resolve()
    return {
        "schema": SCHEMA, "generated_utc": utc(), "root": str(root),
        "generator": {"name": TOOL_NAME, "version": TOOL_VERSION, "path": str(me), "sha256": sha256_file(me)},
        "how_to_read": "pins['tools'][<file name>] (or pins['installed'][<path under root>]) -> path, sha256, version; "
                       "regenerate with `tool_pins.py generate` after a deploy, check with `tool_pins.py verify`",
        "pins_sha256": hashlib.sha256(json.dumps(core, sort_keys=True).encode()).hexdigest(),
        "counts": {"tools": len(tool_entries), "installed": len(inst_entries), "superseded": len(superseded),
                   "superseded_unmatched": len(orphans),
                   "unversioned": sum(1 for e in [*tool_entries.values(), *inst_entries.values()] if e["version"] is None)},
        "tools": tool_entries, "installed": inst_entries, "superseded_unmatched": orphans}


def core_of(pins: dict) -> dict:
    return {"tools": {k: [v["path"], v["sha256"], v["version"]] for k, v in pins["tools"].items()},
            "installed": {k: [v["path"], v["sha256"], v["version"]] for k, v in pins["installed"].items()}}


def build_only(root: Path, previous: dict, only: list[str]) -> dict:
    """The deployed-only re-pin: a fresh scan, of which only the ``only`` entries are taken; every other entry is the
    previous pin unchanged (a pinned file that is now missing stays pinned: verify reports it MISSING)."""

    fresh = build(root)
    unknown = sorted(n for n in only if n not in fresh["tools"] and n not in fresh["installed"])
    if unknown:
        raise SystemExit(f"--only names not found on disk under {root}: {unknown}")
    tools, installed = dict(previous["tools"]), dict(previous["installed"])
    for name in only:
        if name in fresh["tools"]:
            tools[name] = fresh["tools"][name]
        else:
            installed[name] = fresh["installed"][name]
    pins = {**fresh, "tools": dict(sorted(tools.items())), "installed": dict(sorted(installed.items()))}
    pins["mode"] = {"only": sorted(only), "base_pins_sha256": previous.get("pins_sha256"),
                    "base_generated_utc": previous.get("generated_utc")}
    pins["pins_sha256"] = hashlib.sha256(json.dumps(core_of(pins), sort_keys=True).encode()).hexdigest()
    pins["counts"] = {"tools": len(tools), "installed": len(installed),
                      "superseded": sum(len(e.get("superseded", [])) for e in [*tools.values(), *installed.values()]),
                      "superseded_unmatched": len(fresh["superseded_unmatched"]),
                      "unversioned": sum(1 for e in [*tools.values(), *installed.values()] if e["version"] is None)}
    return pins


def cmd_generate(args) -> int:
    root = Path(args.root)
    out = Path(args.out) if args.out else root / "tools" / "TOOL_PINS.json"
    if args.only:
        if not out.is_file():
            raise SystemExit(f"--only re-pins against the current pins, and {out} does not exist")
        pins = build_only(root, load_pins(out), list(dict.fromkeys(args.only)))
    else:
        pins = build(root)
    if out.exists():
        keep = root / "tools" / "_superseded" / f"TOOL_PINS.{time.strftime('%Y%m%dT%H%M%SZ', time.gmtime())}.json"
        keep.parent.mkdir(parents=True, exist_ok=True)
        os.replace(out, keep)
        print(f"previous pins kept as {keep}")
    tmp = out.with_name(f".{out.name}.{os.getpid()}.tmp")
    with open(tmp, "w") as handle:
        json.dump(pins, handle, indent=1)
        handle.write("\n")
        handle.flush()
        os.fsync(handle.fileno())
    os.replace(tmp, out)
    c = pins["counts"]
    if args.only:
        print(f"TOOL_PINS GENERATE --only {' '.join(sorted(set(args.only)))} (every other entry as pinned in "
              f"{pins['mode']['base_pins_sha256']})")
    print(f"TOOL_PINS GENERATE: {c['tools']} tools, {c['installed']} installed, {c['superseded']} superseded "
          f"({c['superseded_unmatched']} unmatched), {c['unversioned']} unversioned; pins_sha256 {pins['pins_sha256']}; "
          f"{out} sha256 {sha256_file(out)}")
    return 0


def load_pins(path: Path) -> dict:
    with open(path) as handle:
        pins = json.load(handle)
    if pins.get("schema") != SCHEMA:
        raise SystemExit(f"{path}: schema {pins.get('schema')!r}, want {SCHEMA}")
    return pins


def cmd_verify(args) -> int:
    root = Path(args.root).resolve()
    pins_path = Path(args.pins) if args.pins else root / "tools" / "TOOL_PINS.json"
    pins = load_pins(pins_path)
    ok = drift = missing = 0
    for section in ("tools", "installed"):
        for key, e in pins[section].items():
            p = root / e["path"]
            if not p.is_file():
                missing += 1
                print(f"MISSING {e['path']} (pinned {e['version']} {e['sha256'][:16]})")
                continue
            sha = sha256_file(p)
            version = read_version(p)[0]
            if sha != e["sha256"] or version != e["version"]:
                drift += 1
                print(f"DRIFT {e['path']}: pinned {e['version']} {e['sha256'][:16]}, on disk {version} {sha[:16]}")
            else:
                ok += 1
    tools, installed, _ = scan(root)
    pinned = {e["path"] for s in ("tools", "installed") for e in pins[s].values()}
    unpinned = [str(p.relative_to(root)).replace(os.sep, "/") for p in [*tools, *installed]]
    unpinned = [u for u in unpinned if u not in pinned]
    for u in unpinned:
        print(f"UNPINNED {u}")
    print(f"TOOL_PINS VERIFY: {ok} ok, {drift} drift, {missing} missing, {len(unpinned)} unpinned "
          f"({pins_path}, generated {pins['generated_utc']}, pins_sha256 {pins['pins_sha256'][:16]})")
    bad = drift or missing or (unpinned and not args.allow_unpinned)
    return 1 if bad else 0


def cmd_get(args) -> int:
    root = Path(args.root)
    pins = load_pins(Path(args.pins) if args.pins else root / "tools" / "TOOL_PINS.json")
    e = pins["tools"].get(args.name) or pins["installed"].get(args.name)
    if e is None:
        print(f"no pin named {args.name}", file=sys.stderr)
        return 1
    print(json.dumps(e, indent=1))
    return 0


def main(argv=None) -> int:
    ap = argparse.ArgumentParser(prog="tool_pins.py", description=__doc__.split("\n\n")[0],
                                 formatter_class=argparse.RawDescriptionHelpFormatter)
    ap.add_argument("--version", action="version", version=f"{TOOL_NAME} {TOOL_VERSION}")
    sub = ap.add_subparsers(dest="cmd", required=True)
    p = sub.add_parser("generate")
    p.add_argument("--root", default=DEFAULT_ROOT)
    p.add_argument("--out")
    p.add_argument("--only", nargs="+", help="deployed-only: re-pin just these names (others copied from the current pins)")
    p = sub.add_parser("verify")
    p.add_argument("--root", default=DEFAULT_ROOT)
    p.add_argument("--pins")
    p.add_argument("--allow-unpinned", action="store_true")
    p = sub.add_parser("get")
    p.add_argument("name")
    p.add_argument("--root", default=DEFAULT_ROOT)
    p.add_argument("--pins")
    args = ap.parse_args(argv)
    return {"generate": cmd_generate, "verify": cmd_verify, "get": cmd_get}[args.cmd](args)


if __name__ == "__main__":
    sys.exit(main())
