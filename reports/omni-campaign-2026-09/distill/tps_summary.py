#!/usr/bin/env python3
"""Print the tps receipt table and the derived budgets, read FROM the receipts.

The results note in this lane quotes numbers.  The only legal source of a number
about this lane is the receipt it was measured into, so the table in the note is
generated by this file rather than typed: run it, paste it, and any number in the
note can be traced to a JSON file and a sha256 by re-running it.

    $PY tps_summary.py --tps-dir /home/cereal/omni-campaign/distill/tps
    $PY tps_summary.py --tps-dir ./tps --format json
"""

from __future__ import annotations

import argparse
import json
from pathlib import Path
from typing import Any

RUNGS = ("10000000", "50000000", "200000000")


def rows(tps_dir: Path) -> list[dict[str, Any]]:
    out: list[dict[str, Any]] = []
    for path in sorted(tps_dir.glob("*.json")):
        receipt = json.loads(path.read_text(encoding="utf-8"))
        if receipt.get("receipt_schema") != "neural-forge-omni-tps-probe-v1":
            continue
        measurement = receipt.get("measurement", {})
        forward = measurement.get("forward_only") or {}
        train = measurement.get("forward_backward_step") or {}
        budgets = receipt.get("derived_budgets", {})
        devices = receipt.get("devices", [])
        peak = {}
        for phase in (train, forward):
            for index, values in (phase.get("torch_memory") or {}).items():
                peak.setdefault(index, values.get("peak_reserved_gb"))
        out.append(
            {
                "file": path.name,
                "cell_id": receipt.get("cell_id"),
                "cell": receipt.get("cell"),
                "mode": receipt.get("mode"),
                "model": Path(str(receipt.get("model_directory", ""))).name,
                "dtype": receipt.get("dtype"),
                "sequence_length": receipt.get("sequence_length"),
                "micro_batch": receipt.get("micro_batch"),
                "tokens_per_step": train.get("tokens_per_step") or forward.get("tokens_per_step"),
                "forward_tokens_per_second": forward.get("tokens_per_second"),
                "train_tokens_per_second": train.get("tokens_per_second"),
                "train_seconds_per_step_median": train.get("seconds_per_step_median"),
                "forward_seconds_per_step_median": forward.get("seconds_per_step_median"),
                "peak_reserved_gb_by_device": peak,
                "peak_host_rss_gb": receipt.get("peak_host_rss_gb"),
                "device_count": receipt.get("device_count"),
                "device_names": [d.get("name") for d in devices],
                "device_uuids": [d.get("uuid") for d in devices],
                "kernel_path": (receipt.get("kernel_path_report") or {}).get("kernel_path"),
                "gradient_checkpointing": (receipt.get("model_facts") or {}).get(
                    "gradient_checkpointing"
                ),
                "trainable_parameters": (receipt.get("model_facts") or {}).get(
                    "trainable_parameters"
                ),
                "non_finite_losses": measurement.get("non_finite_losses"),
                "overflow_steps": (measurement.get("loss_scaler") or {}).get("overflow_steps"),
                "wall_seconds_total": receipt.get("wall_seconds_total"),
                "train_budgets": budgets.get("forward_backward_step", {}),
                "forward_budgets": budgets.get("forward_only", {}),
                "exact_command": receipt.get("exact_command"),
            }
        )
    return out


def markdown(records: list[dict[str, Any]]) -> str:
    lines = [
        "| cell_id | model | mode | dtype | L | micro | fwd tok/s | fwd+bwd+step tok/s | peak VRAM GB (reserved) | peak host RSS GB | devices |",
        "|---|---|---|---|---|---|---|---|---|---|---|",
    ]
    for record in records:
        peak = ", ".join(
            f"{index}:{value}" for index, value in sorted(record["peak_reserved_gb_by_device"].items())
        )
        lines.append(
            "| {cell_id} | {model} | {mode} | {dtype} | {L} | {mb} | {fwd} | {train} | {peak} | {rss} | {dev} |".format(
                cell_id=record["cell_id"],
                model=record["model"],
                mode=record["mode"],
                dtype=record["dtype"],
                L=record["sequence_length"],
                mb=record["micro_batch"],
                fwd=record["forward_tokens_per_second"],
                train=record["train_tokens_per_second"] or "-",
                peak=peak or "-",
                rss=record["peak_host_rss_gb"],
                dev=record["device_count"],
            )
        )
    lines.append("")
    lines.append(
        "| cell_id | phase | tokens/GPU-hour | 10M rung (GPU-h / wall-h) | 50M rung | 200M rung |"
    )
    lines.append("|---|---|---|---|---|---|")
    for record in records:
        for phase, budgets in (
            ("fwd+bwd+step", record["train_budgets"]),
            ("forward-only", record["forward_budgets"]),
        ):
            if not budgets.get("available"):
                continue
            cells = []
            for rung in RUNGS:
                entry = budgets["rungs"][rung]
                cells.append(f"{entry['gpu_hours']} / {entry['wall_clock_hours']}")
            lines.append(
                "| {cell} | {phase} | {tph:,.0f} | {a} | {b} | {c} |".format(
                    cell=record["cell_id"],
                    phase=phase,
                    tph=budgets["tokens_per_gpu_hour"],
                    a=cells[0],
                    b=cells[1],
                    c=cells[2],
                )
            )
    return "\n".join(lines)


def main() -> int:
    ap = argparse.ArgumentParser(description=__doc__)
    ap.add_argument("--tps-dir", type=Path, default=Path(__file__).resolve().parent / "tps")
    ap.add_argument("--format", choices=["markdown", "json"], default="markdown")
    args = ap.parse_args()
    records = rows(args.tps_dir)
    if args.format == "json":
        print(json.dumps(records, indent=1, sort_keys=True))
    else:
        print(markdown(records))
    return 0


if __name__ == "__main__":
    raise SystemExit(main())
